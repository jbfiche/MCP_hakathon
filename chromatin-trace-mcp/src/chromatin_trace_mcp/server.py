def _write_snr_sweep_plot(
    output_path: Path,
    first: SNRFilterDatasetResult,
    second: SNRFilterDatasetResult,
) -> None:
    """Plot the retained-row effect of the SNR thresholds."""
    plt = _plot_imports()
    figure, axis = plt.subplots(figsize=(8.5, 4.2))
    for dataset, color in zip((first, second), ("#1F77B4", "#D62728"), strict=True):
        thresholds = [point.threshold for point in dataset.points]
        retained = [point.localization_retained_fraction * 100 for point in dataset.points]
        trace_retained = [point.trace_retained_fraction * 100 for point in dataset.points]
        axis.plot(thresholds, retained, marker="o", label=f"{dataset.dataset_name} localizations", color=color)
        axis.plot(thresholds, trace_retained, marker="s", linestyle="--", label=f"{dataset.dataset_name} traces", color=color, alpha=0.75)
    axis.set_title("Effect of SNR filtering on retained rows", fontsize=12, fontweight="bold")
    axis.set_xlabel("SNR threshold", fontsize=10)
    axis.set_ylabel("Rows retained (%)", fontsize=10)
    axis.set_ylim(0, 105)
    axis.grid(alpha=0.25)
    axis.legend(fontsize=8, frameon=False, ncol=2)
    figure.tight_layout()
    figure.savefig(output_path, dpi=180, bbox_inches="tight")
    plt.close(figure)


def _write_snr_histogram_plots(
    output_paths: dict[str, Path],
    datasets: list[tuple[SNRFilterDatasetResult, object]],
    thresholds: list[float],
    intensity_columns: list[str],
) -> None:
    """Plot original, removed, and retained distributions for every condition."""
    plt = _plot_imports()
    for column in intensity_columns:
        figure, axes = plt.subplots(
            len(datasets), len(thresholds),
            figsize=(4.1 * len(thresholds), 3.0 * len(datasets)),
            squeeze=False,
        )
        for row, (dataset, localization_table) in enumerate(datasets):
            snr_values = _numeric_values(localization_table, "snr")
            original_values = _numeric_values(localization_table, column)
            finite_original = original_values[np.isfinite(original_values)]
            if not len(finite_original):
                continue
            bins = np.histogram_bin_edges(finite_original, bins=35)
            for col_index, threshold in enumerate(thresholds):
                axis = axes[row, col_index]
                keep = np.isfinite(snr_values) & (snr_values >= threshold)
                kept = original_values[keep & np.isfinite(original_values)]
                removed = original_values[(~keep) & np.isfinite(original_values)]
                axis.hist(finite_original, bins=bins, color="#B8B8B8", alpha=0.45, label="original")
                axis.hist(removed, bins=bins, color="#D62728", alpha=0.58, label="removed")
                axis.hist(kept, bins=bins, color="#1F77B4", alpha=0.58, label="kept")
                axis.set_title(f"{dataset.dataset_name}\nSNR >= {threshold:g}", fontsize=9)
                axis.tick_params(labelsize=7)
                axis.grid(alpha=0.2)
                if row == len(datasets) - 1:
                    axis.set_xlabel(column, fontsize=8)
                if col_index == 0:
                    axis.set_ylabel("localizations", fontsize=8)
                if row == 0 and col_index == 0:
                    axis.legend(fontsize=7, frameon=False)
        figure.suptitle(f"{column}: original vs removed vs kept localizations", fontsize=12, fontweight="bold")
        figure.tight_layout()
        figure.savefig(output_paths[column], dpi=180, bbox_inches="tight")
        plt.close(figure)


def _write_duplicate_multiplicity_plot(output_path: Path, first: SNRFilterDatasetResult, second: SNRFilterDatasetResult) -> None:
    """Plot trace-level copy multiplicity and retained/dropped copies."""
    plt = _plot_imports()
    categories = ["1", "2", "3", "4+"]
    datasets = [first, second]
    figure, axes = plt.subplots(1, 2, figsize=(11, 4.6))
    colors = ["#4C78A8", "#F58518", "#54A24B"]
    for axis, dataset in zip(axes, datasets, strict=True):
        x = np.arange(len(dataset.points))
        bottom = np.zeros(len(dataset.points))
        for category_name, color in zip(categories, ("#D9E6F2", "#9FC2E3", "#5D8FC5", "#234F84"), strict=True):
            values = []
            for point in dataset.points:
                item = next(item for item in point.trace_copy_multiplicity if item.multiplicity == category_name)
                total = sum(part.groups_after for part in point.trace_copy_multiplicity) or 1
                values.append(100 * item.groups_after / total)
            axis.bar(x, values, bottom=bottom, color=color, label=f"{category_name} copies")
            bottom += np.asarray(values)
        axis.set_xticks(x, [f"SNR >= {point.threshold:g}" for point in dataset.points], rotation=20, ha="right")
        axis.set_ylim(0, 100)
        axis.set_ylabel("Trace/barcode groups (%)")
        axis.set_title(f"{dataset.dataset_name}: copies after filtering", fontweight="bold")
        axis.grid(axis="y", alpha=0.25)
        axis.legend(fontsize=7, frameon=False)
    figure.suptitle("Trace-level copy multiplicity after SNR filtering", fontsize=13, fontweight="bold")
    figure.tight_layout()
    figure.savefig(output_path, dpi=180, bbox_inches="tight")
    plt.close(figure)


@mcp.tool(
    name="snr_filter_sweep",
    title="Compare SNR filtering thresholds",
    description=(
        "Evaluate explicit SNR thresholds for two registered datasets. Filters the "
        "associated localization tables locally, joins retained Buid values to trace "
        "Spot_ID values, summarizes retention and intensity distributions, reports "
        "duplicate multiplicity after each threshold, and writes a compact JSON summary "
        "and PNG plot. Call localization_quality_summary first when thresholds are not "
        "already justified. This tool never modifies input files."
    ),
    annotations=ToolAnnotations(
        read_only_hint=False,
        destructive_hint=False,
        idempotent_hint=False,
        open_world_hint=False,
    ),
)
async def snr_filter_sweep(
    first_dataset: Annotated[str, Field(description="First registered dataset name.")],
    second_dataset: Annotated[str, Field(description="Second registered dataset name.")],
    thresholds: Annotated[
        list[float],
        Field(min_length=1, max_length=5, description="Explicit SNR thresholds to compare."),
    ],
    intensity_columns: Annotated[
        list[Literal["mean_intensity", "flux", "spot_pixel_percentage"]],
        Field(description="Localization numeric columns for distribution summaries and plots."),
    ] = ["mean_intensity", "flux"],
) -> SNRFilterSweepResult:
    """Run a local, non-destructive SNR threshold comparison for two datasets."""
    if first_dataset == second_dataset:
        raise ToolError("Choose two different datasets for an SNR sweep.")
    if not intensity_columns:
        raise ToolError("Provide at least one intensity column for the SNR sweep.")
    normalized_thresholds = sorted({float(value) for value in thresholds})
    if any(not math.isfinite(value) or value < 0 or value > 100 for value in normalized_thresholds):
        raise ToolError("SNR thresholds must be finite values between 0 and 100.")
    intensity_columns = list(dict.fromkeys(intensity_columns))

    first_trace_source = _dataset_trace_path(first_dataset)
    second_trace_source = _dataset_trace_path(second_dataset)
    first_trace = _load_dataset_trace(first_dataset)
    second_trace = _load_dataset_trace(second_dataset)
    first_loc_source, first_loc = _load_dataset_localization(first_dataset)
    second_loc_source, second_loc = _load_dataset_localization(second_dataset)
    for name, table in ((first_dataset, first_loc), (second_dataset, second_loc)):
        missing = [column for column in ("Buid", "snr") if column not in table.colnames]
        if missing:
            raise ToolError(f"Localization table for {name!r} lacks required columns: {missing}.")
        for column in intensity_columns:
            if column not in table.colnames:
                raise ToolError(f"Localization table for {name!r} lacks intensity column {column!r}.")
    for name, table in ((first_dataset, first_trace), (second_dataset, second_trace)):
        if "Spot_ID" not in table.colnames:
            raise ToolError(f"Trace table for {name!r} lacks the required Spot_ID column for joining.")

    first_result = SNRFilterDatasetResult(
        dataset_name=first_dataset,
        localization_file=str(first_loc_source.resolve()),
        trace_file=str(first_trace_source.resolve()),
        points=[
            _snr_filter_point(first_dataset, first_trace_source, first_trace, first_loc_source, first_loc, threshold, intensity_columns)
            for threshold in normalized_thresholds
        ],
    )
    second_result = SNRFilterDatasetResult(
        dataset_name=second_dataset,
        localization_file=str(second_loc_source.resolve()),
        trace_file=str(second_trace_source.resolve()),
        points=[
            _snr_filter_point(second_dataset, second_trace_source, second_trace, second_loc_source, second_loc, threshold, intensity_columns)
            for threshold in normalized_thresholds
        ],
    )
    run_directory = _new_run_directory(first_trace_source, "snr-sweep")
    summary_path = run_directory / "snr_filter_sweep.json"
    plot_path = run_directory / "snr_filter_sweep.png"
    histogram_paths = {
        column: run_directory / f"snr_filter_histogram_{column}.png"
        for column in intensity_columns
    }
    duplicate_plot_path = run_directory / "snr_filter_copy_multiplicity.png"
    result = SNRFilterSweepResult(
        thresholds=normalized_thresholds,
        intensity_columns=intensity_columns,
        first=first_result,
        second=second_result,
        artifacts=[],
        notes=[
            "Thresholds were supplied explicitly; call localization_quality_summary first when choosing them.",
            "Localization filtering is joined to traces using localization Buid = trace Spot_ID.",
            "Histogram plots show the original distribution in grey, removed localizations in red, and retained localizations in blue.",
            "Copy-multiplicity plots use trace-level (Trace_ID, Barcode #) groups; they are not allele-splitting results.",
            "No source trace or localization file is modified.",
        ],
    )
    summary_path.write_text(result.model_dump_json(indent=2), encoding="utf-8")
    _write_snr_sweep_plot(plot_path, first_result, second_result)
    _write_snr_histogram_plots(
        histogram_paths,
        [(first_result, first_loc), (second_result, second_loc)],
        normalized_thresholds,
        intensity_columns,
    )
    _write_duplicate_multiplicity_plot(duplicate_plot_path, first_result, second_result)
    artifacts = _artifacts_in(run_directory)
    result.artifacts = artifacts
    return result


def _load_dataset_localization(dataset_name: str):
    """Load a registered dataset's localization table with a useful ToolError."""
    source = _dataset_localization_path(dataset_name)
    try:
        table, _ = LocalizationTable().load(str(source))
    except (SystemExit, Exception) as exc:
        raise ToolError(
            f"Could not load localization table for {dataset_name!r}: {exc}"
        ) from exc
    return source, table


def _numeric_values(table, column: str) -> np.ndarray:
    """Return one numeric column as finite-or-NaN float values."""
    if column not in table.colnames:
        raise ToolError(f"The localization table does not contain a {column!r} column.")
    try:
        return np.asarray(np.ma.asarray(table[column], dtype=float).filled(np.nan))
    except (TypeError, ValueError) as exc:
        raise ToolError(f"Column {column!r} is not numeric: {exc}") from exc


def _numeric_distribution(table, column: str) -> NumericDistribution:
    values = _numeric_values(table, column)
    finite = values[np.isfinite(values)]
    if len(finite) == 0:
        return NumericDistribution(
            column=column,
            finite_count=0,
            missing_or_nonfinite_count=len(values),
            minimum=None,
            p10=None,
            median=None,
            p90=None,
            p99=None,
            maximum=None,
            mean=None,
            standard_deviation=None,
        )
    return NumericDistribution(
        column=column,
        finite_count=len(finite),
        missing_or_nonfinite_count=len(values) - len(finite),
        minimum=float(np.min(finite)),
        p10=float(np.percentile(finite, 10)),
        median=float(np.median(finite)),
        p90=float(np.percentile(finite, 90)),
        p99=float(np.percentile(finite, 99)),
        maximum=float(np.max(finite)),
        mean=float(np.mean(finite)),
        standard_deviation=float(np.std(finite)),
    )


def _unique_string_count(table, column: str) -> int:
    if column not in table.colnames:
        return 0
    return len({str(value) for value in table[column]})


def _duplicate_bucket_values(table, grouping_columns: tuple[str, ...]) -> tuple[dict[str, int], int, int]:
    missing = [column for column in grouping_columns if column not in table.colnames]
    if missing:
        raise ToolError(f"Table lacks grouping columns: {missing}.")
    multiplicities = Counter(
        zip(*(table[column] for column in grouping_columns), strict=True)
    )
    counts = list(multiplicities.values())
    buckets = {
        "zero": sum(count == 1 for count in counts),
        "one": sum(count == 2 for count in counts),
        "two": sum(count == 3 for count in counts),
        "more_than_two": sum(count > 3 for count in counts),
    }
    return buckets, sum(max(count - 1, 0) for count in counts), max(counts, default=0)


def _duplicate_stats_for_table(
    dataset_name: str,
    table_kind: Literal["trace", "localization"],
    source: Path,
    table,
) -> DuplicateMultiplicityStats:
    grouping_columns = (
        ("Trace_ID", "Barcode #")
        if table_kind == "trace"
        else ("ROI #", "CellID #", "Barcode #")
    )
    buckets, duplicate_rows, maximum_group_size = _duplicate_bucket_values(
        table, grouping_columns
    )
    return DuplicateMultiplicityStats(
        dataset_name=dataset_name,
        table_kind=table_kind,
        source_file=str(source.resolve()),
        grouping_columns=list(grouping_columns),
        row_count=len(table),
        unique_group_count=sum(buckets.values()),
        zero_duplicate_groups=buckets["zero"],
        one_duplicate_groups=buckets["one"],
        two_duplicate_groups=buckets["two"],
        more_than_two_duplicate_groups=buckets["more_than_two"],
        duplicate_rows=duplicate_rows,
        maximum_group_size=maximum_group_size,
    )


def _duplicate_multiplicity_stats(
    dataset_name: str,
    table_kind: Literal["trace", "localization"],
) -> DuplicateMultiplicityStats:
    """Count duplicate multiplicities without modifying the source table."""
    if table_kind == "trace":
        source = _dataset_trace_path(dataset_name)
        table = _load_dataset_trace(dataset_name)
        grouping_columns = ("Trace_ID", "Barcode #")
    else:
        source, table = _load_dataset_localization(dataset_name)
    return _duplicate_stats_for_table(dataset_name, table_kind, source, table)


@mcp.tool(
    name="duplicate_statistics",
    title="Summarize duplicate multiplicities",
    description=(
        "Compare two registered datasets and count grouping keys with 0, 1, 2, or "
        "more than 2 duplicate occurrences. For trace tables, a group is "
        "(Trace_ID, Barcode #). For localization tables, a group is "
        "(ROI #, CellID #, Barcode #). This is a read-only summary and does not "
        "remove duplicates or modify input files. Register both datasets with "
        "localization_file when localization statistics are requested."
    ),
    annotations=ToolAnnotations(read_only_hint=True, open_world_hint=False),
)
async def duplicate_statistics(
    first_dataset: Annotated[str, Field(description="First registered dataset name.")],
    second_dataset: Annotated[str, Field(description="Second registered dataset name.")],
    table_kind: Annotated[
        Literal["trace", "localization"],
        Field(description="Which associated table to analyze."),
    ] = "trace",
) -> DuplicateStatisticsResult:
    """Return a compact duplicate-multiplicity comparison for two datasets."""
    if first_dataset == second_dataset:
        raise ToolError("Choose two different dataset names for duplicate comparison.")
    first = _duplicate_multiplicity_stats(first_dataset, table_kind)
    second = _duplicate_multiplicity_stats(second_dataset, table_kind)
    notes = [
        "0 means the grouping key occurs once and has no duplicate occurrence.",
        "1 means two rows share the grouping key; 2 means three rows share it; >2 means four or more rows share it.",
        "duplicate_rows counts extra rows beyond the first occurrence of each grouping key.",
    ]
    if table_kind == "localization":
        notes.append(
            "Localization groups use ROI #, CellID #, and Barcode #; unique spot IDs are not used as grouping keys."
        )
    return DuplicateStatisticsResult(
        first=first,
        second=second,
        table_kind=table_kind,
        same_grouping_columns=first.grouping_columns == second.grouping_columns,
        notes=notes,
    )


