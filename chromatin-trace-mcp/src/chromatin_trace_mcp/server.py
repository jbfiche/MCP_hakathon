def _coordinate_unit(table) -> str | None:
    """Find a coordinate unit in column units or common pyHiM metadata comments."""
    units = {
        str(table[column].unit)
        for column in ("x", "y", "z")
        if column in table.colnames and getattr(table[column], "unit", None) is not None
    }
    if len(units) == 1:
        return units.pop()
    comments = table.meta.get("comments", [])
    if isinstance(comments, str):
        comments = [comments]
    for comment in comments:
        match = re.search(r"(?:xyz_unit|coordinate_unit)\s*=\s*([^,;\s]+)", str(comment))
        if match:
            return match.group(1)
    return None


def _missing_fraction(table, columns: tuple[str, ...]) -> float | None:
    available = [column for column in columns if column in table.colnames]
    if not available or len(table) == 0:
        return None
    missing = 0
    total = len(table) * len(available)
    for column in available:
        values = np.ma.asarray(table[column])
        mask = np.ma.getmaskarray(values)
        missing += int(mask.sum())
        try:
            missing += int((~mask & ~np.isfinite(values.filled(np.nan))).sum())
        except TypeError:
            pass
    return missing / total


def _dataset_quality_metrics(dataset_name: str, trace_table) -> DatasetQualityMetrics:
    barcodes = (
        sorted({str(value) for value in trace_table["Barcode #"]})
        if "Barcode #" in trace_table.colnames
        else []
    )
    trace_count = _unique_count(trace_table, "Trace_ID")
    median_rows_per_trace = None
    duplicate_rows = None
    if "Trace_ID" in trace_table.colnames:
        _, counts = np.unique(np.asarray(trace_table["Trace_ID"]), return_counts=True)
        median_rows_per_trace = float(np.median(counts)) if len(counts) else None
        if "Barcode #" in trace_table.colnames:
            pairs = list(zip(trace_table["Trace_ID"], trace_table["Barcode #"]))
            duplicate_rows = len(pairs) - len(set(pairs))

    localization_row_count = None
    localization_barcode_count = None
    median_snr = None
    dataset = _resolve_dataset(dataset_name)
    if dataset.localization_file is not None:
        captured = io.StringIO()
        try:
            with redirect_stdout(captured):
                localizations, localization_barcodes = LocalizationTable().load(
                    dataset.localization_file
                )
            localization_row_count = len(localizations)
            localization_barcode_count = len(localization_barcodes)
            if "snr" in localizations.colnames and len(localizations):
                snr = np.ma.asarray(localizations["snr"], dtype=float).filled(np.nan)
                median_snr = float(np.nanmedian(snr))
        except (SystemExit, Exception) as exc:
            raise ToolError(
                f"Could not calculate localization metrics for {dataset_name!r}: {exc}"
            ) from exc

    return DatasetQualityMetrics(
        dataset_name=dataset_name,
        trace_row_count=len(trace_table),
        trace_count=trace_count,
        roi_count=_unique_count(trace_table, "ROI #"),
        barcode_count=_unique_count(trace_table, "Barcode #"),
        barcodes=barcodes,
        median_rows_per_trace=median_rows_per_trace,
        coordinate_missing_fraction=_missing_fraction(trace_table, ("x", "y", "z")),
        duplicate_trace_barcode_rows=duplicate_rows,
        localization_row_count=localization_row_count,
        localization_barcode_count=localization_barcode_count,
        median_localization_snr=median_snr,
    )


@mcp.tool(
    name="compare_datasets",
    title="Compare two chromatin-tracing datasets",
    description=(
        "Compare two registered datasets for technical compatibility. Checks required "
        "columns, coordinate units, barcode overlap, schemas, missing coordinates, "
        "duplicate trace/barcode rows, dataset sizes, and localization SNR when an "
        "associated localization table is available. This is a structural QC result, "
        "not a biological significance test."
    ),
    annotations=ToolAnnotations(read_only_hint=True, open_world_hint=False),
)
async def compare_datasets(
    first_dataset: Annotated[str, Field(description="First registered dataset name.")],
    second_dataset: Annotated[str, Field(description="Second registered dataset name.")],
) -> DatasetComparisonResult:
    """Produce an explainable, objective comparison of two trace datasets."""
    if first_dataset == second_dataset:
        raise ToolError("Choose two different dataset names for comparison.")
    first_table = _load_dataset_trace(first_dataset)
    second_table = _load_dataset_trace(second_dataset)
    first_columns = set(first_table.colnames)
    second_columns = set(second_table.colnames)
    first_barcodes = {str(value) for value in first_table["Barcode #"]} if "Barcode #" in first_columns else set()
    second_barcodes = {str(value) for value in second_table["Barcode #"]} if "Barcode #" in second_columns else set()
    shared = first_barcodes & second_barcodes
    first_unit = _coordinate_unit(first_table)
    second_unit = _coordinate_unit(second_table)
    reasons: list[str] = []
    warnings: list[str] = []

    missing_first = sorted(REQUIRED_TRACE_COLUMNS - first_columns)
    missing_second = sorted(REQUIRED_TRACE_COLUMNS - second_columns)
    if missing_first:
        reasons.append(f"{first_dataset} lacks required columns: {missing_first}.")
    if missing_second:
        reasons.append(f"{second_dataset} lacks required columns: {missing_second}.")
    if first_unit and second_unit and first_unit != second_unit:
        reasons.append(
            f"Coordinate units differ ({first_dataset}: {first_unit}; "
            f"{second_dataset}: {second_unit})."
        )
    if first_barcodes and second_barcodes and not shared:
        reasons.append("The datasets have no barcode identifiers in common.")

    if first_columns != second_columns:
        warnings.append("The trace tables do not have identical column schemas.")
    if first_barcodes != second_barcodes:
        warnings.append("The datasets do not contain exactly the same barcode set.")
    if first_unit is None or second_unit is None:
        warnings.append("A coordinate unit is missing, so unit compatibility is unverified.")

    first_metrics = _dataset_quality_metrics(first_dataset, first_table)
    second_metrics = _dataset_quality_metrics(second_dataset, second_table)
    for metrics in (first_metrics, second_metrics):
        if metrics.coordinate_missing_fraction and metrics.coordinate_missing_fraction > 0:
            warnings.append(
                f"{metrics.dataset_name} has missing/non-finite coordinate values "
                f"({metrics.coordinate_missing_fraction:.2%})."
            )
        if metrics.duplicate_trace_barcode_rows:
            warnings.append(
                f"{metrics.dataset_name} contains "
                f"{metrics.duplicate_trace_barcode_rows} repeated trace/barcode rows."
            )

    status: Literal["compatible", "compatible_with_warnings", "not_comparable"]
    if reasons:
        status = "not_comparable"
    elif warnings:
        status = "compatible_with_warnings"
    else:
        status = "compatible"
    if not reasons:
        reasons.append(
            "Required trace columns, coordinate units, and barcode overlap permit "
            "direct structural comparison."
        )

    return DatasetComparisonResult(
        first=first_metrics,
        second=second_metrics,
        status=status,
        comparable=status != "not_comparable",
        shared_barcodes=sorted(shared),
        only_in_first=sorted(first_barcodes - second_barcodes),
        only_in_second=sorted(second_barcodes - first_barcodes),
        same_columns=first_columns == second_columns,
        columns_only_in_first=sorted(first_columns - second_columns),
        columns_only_in_second=sorted(second_columns - first_columns),
        coordinate_unit_first=first_unit,
        coordinate_unit_second=second_unit,
        reasons=reasons,
        warnings=warnings,
    )


