def _snr_filter_point(
    dataset_name: str,
    trace_source: Path,
    trace_table,
    localization_source: Path,
    localization_table,
    threshold: float,
    intensity_columns: list[str],
) -> SNRFilterPoint:
    snr_values = _numeric_values(localization_table, "snr")
    retained_mask = np.isfinite(snr_values) & (snr_values >= threshold)
    filtered_localizations = localization_table[retained_mask]
    retained_buids = (
        {str(value) for value in filtered_localizations["Buid"]}
        if "Buid" in filtered_localizations.colnames
        else set()
    )
    retained_trace_mask = np.array(
        [str(value) in retained_buids for value in trace_table["Spot_ID"]],
        dtype=bool,
    )
    filtered_traces = trace_table[retained_trace_mask]
    trace_spot_ids = {str(value) for value in trace_table["Spot_ID"]}
    duplicate_stats = _duplicate_stats_for_table(
        dataset_name,
        "localization",
        localization_source,
        filtered_localizations,
    )
    copy_multiplicity = _trace_copy_multiplicity(trace_table, filtered_traces)
    return SNRFilterPoint(
        threshold=threshold,
        localization_rows_before=len(localization_table),
        localization_rows_retained=len(filtered_localizations),
        localization_retained_fraction=(
            len(filtered_localizations) / len(localization_table)
            if len(localization_table)
            else 0.0
        ),
        unique_buids_retained=len(retained_buids),
        unique_barcodes_retained=_unique_string_count(filtered_localizations, "Barcode #"),
        unique_rois_retained=_unique_string_count(filtered_localizations, "ROI #"),
        unique_cells_retained=(
            _unique_string_count(filtered_localizations, "CellID #")
            if "CellID #" in filtered_localizations.colnames
            else None
        ),
        trace_rows_before=len(trace_table),
        trace_rows_retained=len(filtered_traces),
        trace_retained_fraction=len(filtered_traces) / len(trace_table) if len(trace_table) else 0.0,
        unique_traces_retained=_unique_string_count(filtered_traces, "Trace_ID"),
        unmatched_localization_buids=len(retained_buids - trace_spot_ids),
        intensity_distributions=[
            _numeric_distribution(filtered_localizations, column)
            for column in intensity_columns
        ],
        duplicate_statistics=duplicate_stats,
        trace_copy_multiplicity=copy_multiplicity,
    )


def _trace_copy_multiplicity(trace_table, filtered_traces) -> list[CopyMultiplicityRetention]:
    """Summarize copies per (Trace_ID, Barcode #) group before and after filtering."""
    categories = ("1", "2", "3", "4+")
    before_counts = Counter(
        (str(trace_id), str(barcode))
        for trace_id, barcode in zip(trace_table["Trace_ID"], trace_table["Barcode #"], strict=True)
    )
    after_counts = Counter(
        (str(trace_id), str(barcode))
        for trace_id, barcode in zip(filtered_traces["Trace_ID"], filtered_traces["Barcode #"], strict=True)
    )

    def category(count: int) -> str:
        return str(count) if count <= 3 else "4+"

    result = []
    for label in categories:
        groups_before = sum(category(count) == label for count in before_counts.values())
        rows_before = sum(count for key, count in before_counts.items() if category(count) == label)
        rows_retained = sum(
            after_counts.get(key, 0)
            for key, count in before_counts.items()
            if category(count) == label
        )
        groups_after = sum(
            after_counts.get(key, 0) > 0
            for key, count in before_counts.items()
            if category(count) == label
        )
        result.append(
            CopyMultiplicityRetention(
                multiplicity=label,
                groups_before=groups_before,
                groups_after=groups_after,
                rows_before=rows_before,
                rows_retained=rows_retained,
                rows_dropped=rows_before - rows_retained,
            )
        )
    return result


