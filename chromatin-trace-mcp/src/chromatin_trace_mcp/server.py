def configured_trace_path(*, for_tool: bool = False) -> Path:
    """Return the trace path selected by the server's environment variable."""
    error_type = ToolError if for_tool else ResourceError
    raw_path = os.environ.get(TRACE_PATH_ENV)
    if not raw_path:
        raise error_type(
            f"No trace file is configured. Set {TRACE_PATH_ENV} to an ECSV file path "
            "and restart the MCP server."
        )

    path = Path(raw_path).expanduser()
    if not path.is_file():
        raise error_type(
            f"The configured trace file does not exist or is not a file: {path}"
        )
    if path.suffix.lower() != ".ecsv":
        raise error_type(
            f"The configured trace must have the .ecsv extension, but received: {path.name}"
        )
    return path


def configured_localization_path() -> Path:
    """Return the separate localization table configured for QC analysis."""
    raw_path = os.environ.get(LOCALIZATION_PATH_ENV)
    if not raw_path:
        raise ToolError(
            f"No localization file is configured. Set {LOCALIZATION_PATH_ENV} to "
            "a localization ECSV file and restart the MCP server. This is not the "
            f"same table as {TRACE_PATH_ENV}."
        )

    path = Path(raw_path).expanduser()
    if not path.is_file():
        raise ToolError(
            f"The configured localization file does not exist or is not a file: {path}"
        )
    if path.suffix.lower() != ".ecsv":
        raise ToolError(
            "The configured localization table must have the .ecsv extension, "
            f"but received: {path.name}"
        )
    return path.resolve()


def _validate_dataset_name(name: str) -> None:
    if re.fullmatch(DATASET_NAME_PATTERN, name) is None:
        raise ToolError(
            "Dataset names must be 1-64 characters and contain only letters, "
            "numbers, dots, underscores, or hyphens."
        )


def _validated_ecsv_path(raw_path: str, kind: str) -> Path:
    path = Path(raw_path).expanduser().resolve()
    if not path.is_file():
        raise ToolError(f"The {kind} file does not exist or is not a file: {path}")
    if path.suffix.lower() != ".ecsv":
        raise ToolError(f"The {kind} file must have the .ecsv extension: {path}")
    return path


def _current_dataset() -> DatasetInfo | None:
    raw_trace = os.environ.get(TRACE_PATH_ENV)
    if not raw_trace:
        return None
    trace = Path(raw_trace).expanduser().resolve()
    raw_localization = os.environ.get(LOCALIZATION_PATH_ENV)
    localization = (
        Path(raw_localization).expanduser().resolve() if raw_localization else None
    )
    return DatasetInfo(
        name="current",
        trace_file=str(trace),
        localization_file=str(localization) if localization else None,
    )


def _catalog_datasets() -> dict[str, tuple[Path, Path | None]]:
    """Load persistent dataset definitions from the optional JSON catalog."""
    raw_catalog_path = os.environ.get(DATASET_CATALOG_ENV)
    if not raw_catalog_path:
        return {}
    catalog_path = Path(raw_catalog_path).expanduser().resolve()
    if not catalog_path.is_file():
        raise ToolError(f"Dataset catalog does not exist: {catalog_path}")
    try:
        document = json.loads(catalog_path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as exc:
        raise ToolError(f"Could not read dataset catalog {catalog_path}: {exc}") from exc
    if not isinstance(document, dict):
        raise ToolError("The dataset catalog must be a JSON object keyed by dataset name.")

    datasets: dict[str, tuple[Path, Path | None]] = {}
    for name, definition in document.items():
        _validate_dataset_name(name)
        if name == "current":
            raise ToolError("The catalog cannot use the reserved dataset name 'current'.")
        if not isinstance(definition, dict) or not isinstance(
            definition.get("trace_file"), str
        ):
            raise ToolError(
                f"Catalog dataset {name!r} must contain a string 'trace_file'."
            )
        trace = _validated_ecsv_path(definition["trace_file"], "trace")
        raw_localization = definition.get("localization_file")
        if raw_localization is not None and not isinstance(raw_localization, str):
            raise ToolError(
                f"Catalog dataset {name!r} has a non-string 'localization_file'."
            )
        if isinstance(raw_localization, str) and not raw_localization.strip():
            raw_localization = None
        localization = (
            _validated_ecsv_path(raw_localization, "localization")
            if raw_localization is not None
            else None
        )
        datasets[name] = (trace, localization)
    return datasets


def _configured_catalog_path() -> Path | None:
    """Return the JSON catalog path from the environment, or None if unset."""
    raw_catalog_path = os.environ.get(DATASET_CATALOG_ENV)
    if not raw_catalog_path:
        return None
    return Path(raw_catalog_path).expanduser().resolve()


def _read_catalog_document(catalog_path: Path) -> dict:
    """Read the raw catalog JSON (without checking that listed files exist).

    A missing file is an empty catalog; it is created on the first registration.
    """
    if not catalog_path.exists():
        return {}
    try:
        document = json.loads(catalog_path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as exc:
        raise ToolError(
            f"Could not read dataset catalog {catalog_path}: {exc}. "
            "Fix or remove the file, then register the dataset again."
        ) from exc
    if not isinstance(document, dict):
        raise ToolError("The dataset catalog must be a JSON object keyed by dataset name.")
    return document


def _catalog_entry_paths(name: str) -> tuple[Path, Path | None] | None:
    """Paths recorded in the catalog for one name, or None if it is not there."""
    catalog_path = _configured_catalog_path()
    if catalog_path is None:
        return None
    entry = _read_catalog_document(catalog_path).get(name)
    if not isinstance(entry, dict) or not isinstance(entry.get("trace_file"), str):
        return None
    raw_localization = entry.get("localization_file")
    localization = (
        Path(raw_localization).expanduser().resolve()
        if isinstance(raw_localization, str) and raw_localization.strip()
        else None
    )
    return Path(entry["trace_file"]).expanduser().resolve(), localization


def _save_to_catalog(name: str, trace: Path, localization: Path | None) -> Path | None:
    """Add or update one dataset entry in the JSON catalog, keeping all other entries.

    The file is written to a temporary file first and then renamed, so an
    interrupted write never leaves a half-written catalog. Returns the catalog
    path, or None when no catalog is configured.
    """
    catalog_path = _configured_catalog_path()
    if catalog_path is None:
        return None
    if not catalog_path.parent.is_dir():
        raise ToolError(
            f"Cannot save the dataset catalog: folder {catalog_path.parent} does not exist."
        )
    document = _read_catalog_document(catalog_path)

    document[name] = {
        "trace_file": str(trace),
        "localization_file": str(localization) if localization else "",
    }
    temporary_path = catalog_path.with_name(
        f".{catalog_path.name}.{uuid4().hex[:8]}.tmp"
    )
    try:
        temporary_path.write_text(
            json.dumps(document, indent=2, ensure_ascii=False) + "\n", encoding="utf-8"
        )
        os.replace(temporary_path, catalog_path)
    except OSError as exc:
        temporary_path.unlink(missing_ok=True)
        raise ToolError(f"Could not save dataset catalog {catalog_path}: {exc}") from exc
    return catalog_path


def _resolve_dataset(name: str) -> DatasetInfo:
    if name == "current":
        current = _current_dataset()
        if current is None:
            raise ToolError(
                f"Dataset 'current' is not configured. Set {TRACE_PATH_ENV}, or "
                "register a named dataset and use its name."
            )
        _validated_ecsv_path(current.trace_file, "trace")
        if current.localization_file is not None:
            _validated_ecsv_path(current.localization_file, "localization")
        return current
    available_datasets = {**_catalog_datasets(), **_DATASETS}
    if name not in available_datasets:
        available = sorted(available_datasets)
        raise ToolError(
            f"Unknown dataset {name!r}. Available named datasets: {available}."
        )
    trace, localization = available_datasets[name]
    return DatasetInfo(
        name=name,
        trace_file=str(trace),
        localization_file=str(localization) if localization else None,
    )


def _dataset_trace_path(name: str) -> Path:
    return Path(_resolve_dataset(name).trace_file)


def _dataset_localization_path(name: str) -> Path:
    if name == "current":
        return configured_localization_path()
    dataset = _resolve_dataset(name)
    if dataset.localization_file is None:
        raise ToolError(
            f"Dataset {name!r} has no associated localization ECSV file."
        )
    return Path(dataset.localization_file)


def output_root(source_path: Path) -> Path:
    """Return and create the directory reserved for generated MCP artifacts."""
    configured = os.environ.get(OUTPUT_DIR_ENV)
    root = (
        Path(configured).expanduser()
        if configured
        else source_path.parent / "mcp_outputs"
    )
    try:
        root.mkdir(parents=True, exist_ok=True)
    except OSError as exc:
        raise ToolError(f"Could not create the MCP output directory {root}: {exc}") from exc
    if not root.is_dir():
        raise ToolError(f"The configured MCP output location is not a directory: {root}")
    return root.resolve()


def _new_run_directory(source_path: Path, operation: str) -> Path:
    """Create an isolated directory so traceratops never overwrites an earlier run."""
    run_directory = output_root(source_path) / f"{operation}-{uuid4().hex[:12]}"
    run_directory.mkdir()
    return run_directory


def _artifacts_in(directory: Path) -> list[GeneratedArtifact]:
    """Describe every generated file in a run directory."""
    return [
        GeneratedArtifact(path=str(path.resolve()), size_bytes=path.stat().st_size)
        for path in sorted(directory.iterdir())
        if path.is_file()
    ]


def load_current_trace():
    """Load the configured ECSV as an Astropy Table using traceratops."""
    path = configured_trace_path(for_tool=True)
    try:
        return read_table_from_ecsv(path)
    except Exception as exc:
        raise ToolError(f"traceratops could not open the ECSV trace: {exc}") from exc


def _load_dataset_trace(dataset_name: str):
    path = _dataset_trace_path(dataset_name)
    try:
        return read_table_from_ecsv(path)
    except Exception as exc:
        raise ToolError(
            f"traceratops could not open trace for dataset {dataset_name!r}: {exc}"
        ) from exc


def _unique_count(table, column_name: str) -> int | None:
    """Count unique values when a traceratops table contains the requested column."""
    if column_name not in table.colnames:
        return None
    return len(set(table[column_name]))


@mcp.tool(
    name="register_dataset",
    title="Register a chromatin-tracing dataset",
    description=(
        "Associate a short dataset name with a trace ECSV (one ROI or a merged "
        "experiment) and, optionally, its localization ECSV. The dataset is saved to "
        "the JSON catalog when one is configured, so it is still available after the "
        "server restarts; otherwise it lasts for this server process only. Input files "
        "are never modified. Registering an existing name with the same files does "
        "nothing; replacing an existing name with different files requires "
        "overwrite=true."
    ),
    annotations=ToolAnnotations(
        read_only_hint=False,
        destructive_hint=False,
        idempotent_hint=True,
        open_world_hint=False,
    ),
)
async def register_dataset(
    name: Annotated[str, Field(pattern=DATASET_NAME_PATTERN)],
    trace_file: Annotated[str, Field(description="Path to the trace ECSV file.")],
    localization_file: Annotated[
        str | None,
        Field(description="Path to the associated localization ECSV, when available."),
    ] = None,
    overwrite: Annotated[
        bool,
        Field(
            description=(
                "Replace an existing dataset of the same name that points to "
                "different files. Only set this when the user asked to replace it."
            )
        ),
    ] = False,
) -> RegisteredDataset:
    """Validate, register and (when a catalog is configured) save one dataset."""
    _validate_dataset_name(name)
    if name == "current":
        raise ToolError("The name 'current' is reserved for environment configuration.")
    trace = _validated_ecsv_path(trace_file, "trace")
    if localization_file is not None and not localization_file.strip():
        localization_file = None
    localization = (
        _validated_ecsv_path(localization_file, "localization")
        if localization_file is not None
        else None
    )

    requested = (trace, localization)
    for existing in (_DATASETS.get(name), _catalog_entry_paths(name)):
        if existing is not None and existing != requested and not overwrite:
            existing_trace, existing_localization = existing
            raise ToolError(
                f"A dataset named {name!r} already exists with different files "
                f"(trace: {existing_trace}; localization: "
                f"{existing_localization or 'none'}). Choose another name, or call "
                "register_dataset again with overwrite=true if the user wants to "
                "replace it."
            )

    captured = io.StringIO()
    try:
        with redirect_stdout(captured):
            read_table_from_ecsv(trace)
            if localization is not None:
                LocalizationTable().load(str(localization))
    except SystemExit as exc:
        raise ToolError("traceratops could not load the localization table.") from exc
    except Exception as exc:
        raise ToolError(f"traceratops could not register the dataset: {exc}") from exc

    catalog_path = _save_to_catalog(name, trace, localization)
    _DATASETS[name] = (trace, localization)
    if catalog_path is not None:
        note = f"Saved {name!r} to {catalog_path}; it will still be available after a restart."
    else:
        note = (
            f"Registered {name!r} for this session only: no catalog is configured "
            f"({DATASET_CATALOG_ENV}), so it will be forgotten when the server restarts."
        )
    return RegisteredDataset(
        name=name,
        trace_file=str(trace),
        localization_file=str(localization) if localization else None,
        saved_to_catalog=str(catalog_path) if catalog_path is not None else None,
        note=note,
    )


@mcp.tool(
    name="list_datasets",
    title="List registered datasets",
    description=(
        "List named datasets available to the MCP server. The environment-configured "
        "files appear under the reserved name 'current'."
    ),
    annotations=ToolAnnotations(read_only_hint=True, open_world_hint=False),
)
async def list_datasets() -> DatasetListResult:
    """Return the current environment dataset and session registrations."""
    names = sorted(set(_catalog_datasets()) | set(_DATASETS))
    datasets = [_resolve_dataset(name) for name in names]
    current = _current_dataset()
    if current is not None:
        datasets.insert(0, current)
    return DatasetListResult(datasets=datasets)


@mcp.tool(
    name="inspect_dataset",
    title="Inspect a named chromatin dataset",
    description=(
        "Open a named dataset's trace with traceratops and summarize its columns, "
        "metadata, traces, barcodes, and ROIs. Use list_datasets first when needed."
    ),
    annotations=ToolAnnotations(read_only_hint=True, open_world_hint=False),
)
async def inspect_dataset(
    dataset_name: Annotated[str, Field(description="Registered dataset name.")]
) -> TraceSummary:
    """Inspect one named trace table."""
    path = _dataset_trace_path(dataset_name)
